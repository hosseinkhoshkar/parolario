// Validate immutable Italian references/sidecars and generate only runtime data.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { discoverExampleCatalog, validateExampleCatalog } from './example-catalog.mjs'
const lessons = await discoverExampleCatalog()
const issues = validateExampleCatalog(lessons)
if (issues.length) throw new Error(issues.join('\n'))
const examples = {}
for (const lesson of lessons) for (const row of lesson.catalog.entries) {
  const entryId = `it-a1-l${String(lesson.catalog.lessonNumber).padStart(2, '0')}-${String(row.row).padStart(3, '0')}`
  examples[entryId] = row.additionalExamples.map((example, index) => ({ exampleId: `${entryId}-additional-${index + 1}`, ...example }))
}
async function writeChanged(target, value) {
  let previous
  try { previous = await readFile(target, 'utf8') } catch { /* First generation. */ }
  if (previous !== value) await writeFile(target, value)
}
for (const lesson of lessons) {
  const target = lesson.catalog.lessonNumber === 1 ? 'italian-source.json' : `italian-source-${String(lesson.catalog.lessonNumber).padStart(2, '0')}.json`
  await writeChanged(`src/content/${target}`, JSON.stringify(lesson.rows, null, 2) + '\n')
}
await writeChanged('src/content/additional-examples.ts', '// Generated by npm run sync:examples. Do not edit.\n'
  + "import type { Example } from '../contracts/index.ts'\n\n"
  + 'export const additionalExamplesByEntry: Record<string, Example[]> = ' + JSON.stringify(examples, null, 2) + '\n')
await mkdir('test-results', { recursive: true })
const report = { lessonFiles: lessons.length, entries: lessons.reduce((sum, item) => sum + item.rows.length, 0),
  quotedExamples: lessons.reduce((sum, item) => sum + item.rows.length, 0), additionalExamples: Object.keys(examples).length * 2,
  activeEntries: Object.keys(examples).length, structuralValidation: 'passed', note: 'Source excerpts preserved; structure is not native-speaker certification.' }
await writeFile('test-results/examples-report.json', JSON.stringify(report, null, 2))
console.log(JSON.stringify(report))
